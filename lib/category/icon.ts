/**
 * The statically-available icon for a category, if any. Prefers the stored
 * `icon` name, then the legacy emoji mapping. Returns `undefined` when the
 * chosen icon lives outside the curated set — the caller (`CategoryIcon`) then
 * defers to the lazily-loaded full catalogue.
 */
export function staticIconFor(category: {
  icon?: string;
  emoji?: string;
}): LucideIcon | undefined {
  return (
    iconByName(category.icon) ??
    iconByName(category.emoji ? EMOJI_ICON_NAMES[category.emoji] : undefined)
  );
}
