/** Fallback for a missing/unknown icon — a neutral money glyph, never blank. */
export const DEFAULT_CATEGORY_ICON: LucideIcon = CircleDollarSign;

/** A curated icon by name, if it's in the statically-bundled set. */
export function iconByName(name: string | undefined): LucideIcon | undefined {
  if (!name) return undefined;
  return RENDER_ICONS[name];
}

